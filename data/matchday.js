export function getMatchdayLineup(team, opponent) {
  const reports = lineupReports
    .filter((report) => report.teams[team])
    .sort((a, b) => new Date(b.reportedAt) - new Date(a.reportedAt));
  const exact = reports.find((report) => report.teams[opponent]);
  const report = exact || reports[0];
  if (!report) return null;
  return {
    ...report.teams[team],
    reportId: report.id,
    reportedAt: report.reportedAt,
    context: report.context,
    source: report.source,
    exactMatch: Boolean(exact),
  };
}
